/** The first word among `texts` (keys split at camel case, labels at spaces) that names an icon. */
export function iconFromWords(...texts: string[]): IconName | undefined {
  for (const text of texts) {
    const words = text
      .replace(/([a-z])([A-Z])/g, "$1 $2")
      .toLowerCase()
      .split(/[^a-z]+/)
      .filter(Boolean);
    for (const word of words) {
      const found =
        WORD_ICONS[word] ?? (word.endsWith("s") ? WORD_ICONS[word.slice(0, -1)] : undefined);
      if (found) return found;
    }
  }
  return undefined;
}

export const iconNames = Object.keys(PATHS) as IconName[];

/** An inline line icon, hidden from assistive technology (its control carries the name). */
export function icon(name: IconName): SVGSVGElement {
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("viewBox", "0 0 16 16");
  svg.setAttribute("aria-hidden", "true");
  svg.setAttribute("focusable", "false");
  svg.classList.add("icon");
  const path = document.createElementNS("http://www.w3.org/2000/svg", "path");
  path.setAttribute("d", PATHS[name]);
  svg.append(path);
  return svg;
}
